// Rebuilds the knot library: bundles src/stations-next/takeaway/knots-gen.ts, runs it and writes
// src/stations-next/takeaway/knots-data.ts. Deterministic: the same code gives the same file. Run by hand after changing
// the path families or the generator: `node scripts/knots-build.mjs`.
import { buildSync } from 'esbuild';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..'), DIR = join(ROOT, 'src', 'stations-next', 'takeaway');
const code = buildSync({ entryPoints: [join(DIR, 'knots-gen.ts')], bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', write: false, logLevel: 'warning' }).outputFiles[0].text;
const file = join(mkdtempSync(join(tmpdir(), 'chakei-knots-')), 'knots-gen.mjs');
writeFileSync(file, code);
const { buildLibrary } = await import(pathToFileURL(file).href);
const t0 = Date.now(), lib = buildLibrary(s => console.log(s));
const rows = lib.data.map(([name, fam, pts, corners]) => `  [${JSON.stringify(name)}, ${JSON.stringify(fam)}, '${pts}', [${corners.join(',')}]],`);
writeFileSync(join(DIR, 'knots-data.ts'), [
  '// Generated by scripts/knots-build.mjs. Do not edit by hand: change knots-gen.ts and run `node scripts/knots-build.mjs`.',
  ...lib.report.map(l => `// ${l}`),
  '// base: the tier each difficulty plays at slider 5; band: the trace band per tier (css px); parSpeed: par speed per tier.',
  `export const KNOT_TUNE = { base: ${JSON.stringify(lib.tune.base).replace(/"(\w+)":/g, '$1: ').replace(/,/g, ', ')}, band: [${lib.tune.band.join(', ')}], parSpeed: [${lib.tune.parSpeed.join(', ')}] } as const;`,
  '// [name, family, points (2 base-64 chars per coordinate, 1/8 px), sharp-corner indexes], tier by tier, 10 patterns each, easiest first',
  'export const KNOT_DATA: readonly (readonly [string, string, string, readonly number[]])[] = [',
  ...rows,
  '];',
  '',
].join('\n'));
console.log(`wrote knots-data.ts: ${lib.data.length} knots in ${((Date.now() - t0) / 1000).toFixed(0)} s`);
