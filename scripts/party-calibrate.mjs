// Sets party mode's card lines, rent and title ladder from the bot, and
// writes them to src/core/party/lines.ts. Run it after any change to the shop's rules, the sim bots, the shops or the stakes:
//   node scripts/party-calibrate.mjs            (both steps, ~10 minutes; `titles` runs step 2 alone on the cached pool)
//
// Each shop of the ladder is set for the team it is for (tests/sim/party-team.js SHOP_TEAM): 屋邨茶記 for a first
// night, 中環早餐 for the "human x1" team (the solo ladder's order), up to 地獄午市 for a sharp one.
// Step 1 (lines): that team plays N real party rounds per round flow in its shop (a room with the
// director, the team's four players at the shop's party seats 樓面 / 水吧 / 廚房 / 收銀 at a person's speed, the computer
// at 樓面's second place and 燒味; the round's money is the room's pay, 樓面 at its real share); the 21-point quantiles of
// each metric go into PARTY_Q[shop]. A tier's line is then the value such a team
// reaches with the tier's aim (80 / 50 / 25%), and the rent is its takings' RENT_Q quantile.
// Step 2 (titles, a fresh process so the new lines are loaded): whole nights by the shop's team through the night's state
// machine, rounds drawn from the step 1 rounds; the title thresholds are the TITLE_Q quantiles of the
// final till over the nights that did not fold, so a mid team ends in 人氣茶記 and only a lucky or strong night reaches
// 茶記傳奇. The test sims (tests/sim/party-*.test.js) check the result on other seeds.
import { writeFileSync, readFileSync, mkdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const LINES = join(ROOT, 'src', 'core', 'party', 'lines.ts');
const CACHE = join(ROOT, 'tests', 'out', 'party-pool.json');
const N = Number(process.env.PARTY_CAL_N || 80), NIGHTS = Number(process.env.PARTY_CAL_NIGHTS || 1000);
const METRICS = ['rev', 'clean', 'calm', 'combo', 'tips', 'fever'];
const TITLE_Q = [.05, .3, .57, .93, .99];   // 排隊名店 (CLIMB_TITLE) at the 57% night (folds take a few points), so a shop's own team climbs on ~40% of nights

const quantiles = (vals, points = 21) => {
  const s = [...vals].sort((a, b) => a - b);
  return Array.from({ length: points }, (_, i) => {
    const x = (s.length - 1) * i / (points - 1), lo = Math.floor(x), hi = Math.min(s.length - 1, lo + 1);
    return Math.round((s[lo] + (s[hi] - s[lo]) * (x - lo)) * 10) / 10;
  });
};

function writeLines(q, titles, cal) {
  const body = `// GENERATED by scripts/party-calibrate.mjs on the shop's rules and the sim bots: do not edit by hand, run the script.
// ${String(cal.shifts)} real in-memory team shifts, each shop played by the team it is for (${Object.entries(cal.teams).map(([s, m]) => `${s}: ${m}`).join(', ')}),
// ${String(cal.nights)} nights per title ladder.
import type { PartyMetric } from './types';

/** The calibration's round flows: 宵夜 uses the dinner flow. */
export type LineKind = 'breakfast' | 'lunch' | 'tea' | 'dinner';
/** 21-point quantiles (0%, 5%, ... 100%) of a round by the team a shop is for, per shop, flow and metric. */
export const PARTY_Q: Record<string, Record<LineKind, Record<PartyMetric, readonly number[]>>> = ${JSON.stringify(q, null, 0).replace(/\],"/g, '],\n    "').replace(/\},"/g, '},\n  "')};
/** The 收舖 title thresholds (5, ascending) per shop and night length in days. */
export const TITLE_LINES: Record<string, Record<string, readonly number[]>> = ${JSON.stringify(titles)};
/** How the tables were made (for the report and the docs). */
export const CALIBRATION = ${JSON.stringify(cal)};
`;
  writeFileSync(LINES, body);
}

if (process.argv[2] === 'titles') {
  const { freshCore } = await import('../tests/sim/core.js');
  const { playNight, SHOP_TEAM } = await import('../tests/sim/party-team.js');
  const C = freshCore(), pool = JSON.parse(readFileSync(CACHE, 'utf8'));
  const titles = {}, folds = {};
  for (const shop of C.SHOP_LADDER) {
    titles[shop] = {};
    for (const days of [1, 2]) {
      const banks = [];
      let folded = 0;
      for (let i = 0; i < NIGHTS; i++) {
        const r = playNight(C, { seed: 900001 + i * 13 + days, pool, cfg: { shop, days } });
        if (r.errs.length) throw new Error(r.errs.join('; '));
        if (r.s.bank < 0) folded++; else banks.push(r.s.bank);
      }
      const s = banks.sort((a, b) => a - b);
      titles[shop][days] = TITLE_Q.map(u => Math.round(s[Math.floor(u * (s.length - 1))] / 100) * 100);
      folds[`${shop} ${String(days)}d`] = Math.round(folded / NIGHTS * 1000) / 10;
      console.log(`titles ${shop} ${String(days)}d (${SHOP_TEAM[shop]}):`, titles[shop][days].join(' / '), ` median $${String(s[Math.floor(s.length / 2)])}, folded ${String(folds[`${shop} ${String(days)}d`])}%`);
    }
  }
  writeLines(C.PARTY_Q, titles, { ...C.CALIBRATION, nights: NIGHTS, folds });
} else {
  const { freshCore } = await import('../tests/sim/core.js');
  const { buildPool, cellKey, metricOf, MODELS, SHOP_TEAM } = await import('../tests/sim/party-team.js');
  const C = freshCore(), t0 = performance.now();
  const cells = C.SHOP_LADDER.map(shop => ({ shop, model: SHOP_TEAM[shop] }));
  const pool = await buildPool({ cells, n: N, seed0: 1 });
  mkdirSync(join(ROOT, 'tests', 'out'), { recursive: true });
  writeFileSync(CACHE, JSON.stringify(pool));
  const q = {};
  for (const shop of C.SHOP_LADDER) {
    q[shop] = {};
    for (const [flow, xs] of Object.entries(pool[cellKey(shop, SHOP_TEAM[shop])])) q[shop][flow] = Object.fromEntries(METRICS.map(m => [m, quantiles(xs.map(x => metricOf(m, x)))]));
  }
  const shifts = Object.keys(pool).length * 4 * N;
  writeLines(q, {}, { shifts, nights: 0, teams: SHOP_TEAM, models: MODELS });
  console.log(`lines: ${String(shifts)} shifts in ${((performance.now() - t0) / 1000).toFixed(0)} s`);
  const r = spawnSync(process.execPath, [import.meta.filename, 'titles'], { stdio: 'inherit' });
  process.exit(r.status ?? 1);
}
