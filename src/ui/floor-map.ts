/* ---------- the atlas (site/art/floor.json + floor_0.webp) ---------- */
interface Part { page: number; x: number; y: number; w: number; h: number; kind: string; anchor: [number, number]; hips?: number; top_h?: number; look?: string; name?: string }
interface Looks { customers: string[]; rules: { pattern: string; members: string[][] }[] }
let atlas: { parts: Record<string, Part>; looks: Looks; pages: HTMLImageElement[]; dishes: string[] } | null = null, atlasLoading = false, atlasFailed = 0;
const ATLAS_RETRY = 30000;   // ms before trying again after a failed load (offline before it was cached)
const isRec = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null;
const num4 = (v: Record<string, unknown>): boolean => ['page', 'x', 'y', 'w', 'h'].every(k => typeof v[k] === 'number');
function isPart(v: unknown): v is Part {
  return isRec(v) && num4(v) && typeof v.kind === 'string' && Array.isArray(v.anchor) && v.anchor.length === 2 && v.anchor.every(n => typeof n === 'number');
}
function isRule(v: unknown): v is Looks['rules'][number] {
  return isRec(v) && typeof v.pattern === 'string' && Array.isArray(v.members) && v.members.every(m => Array.isArray(m) && m.every(s => typeof s === 'string'));
}
async function loadAtlas(): Promise<void> {
  if (atlas || atlasLoading || (atlasFailed && performance.now() - atlasFailed < ATLAS_RETRY)) return;
  atlasLoading = true;
  try {
    const r = await fetch('art/floor.json'), j: unknown = await r.json();
    if (!isRec(j) || !isRec(j.parts) || !Array.isArray(j.pages) || !isRec(j.looks)) throw new Error('floor.json');
    const pages = await Promise.all(j.pages.map(p => new Promise<HTMLImageElement>((ok, bad) => {
      const im = new Image(); im.onload = () => { ok(im); }; im.onerror = () => { bad(new Error(String(p))); };
      im.src = 'art/' + String(p).replace(/\.png$/, '.webp');
    })));
    const parts: Record<string, Part> = {}, L = j.looks;
    for (const [k, v] of Object.entries(j.parts)) if (isPart(v)) parts[k] = v;
    const rules = Array.isArray(L.rules) ? L.rules.filter(isRule) : [];
    const looks: Looks = { customers: Array.isArray(L.customers) ? L.customers.map(String) : [], rules };
    atlas ={ parts, looks, pages, dishes: Object.keys(parts).filter(k => parts[k]?.kind === 'dish') };
    redraw();
  } catch { atlasLoading = false; atlasFailed = performance.now(); }   // offline before it was cached: code art stays
}
