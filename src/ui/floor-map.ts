    const ch = g.state === 'think' ? '睇' : g.state === 'order' ? (!g.take && g.taken ? '寫' : '落') : g.state === 'wait' ? (g.meals && g.meals.some(m => !m.done) ? '等' : '飲') : g.state === 'pay' ? '埋' : '食';
