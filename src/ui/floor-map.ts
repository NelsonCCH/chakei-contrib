const pt = (u: number, v: number, z = 0): { x: number; y: number } => ({ x: ox + (u - v) * HX, y: oy + (u + v) * HY - z });
interface Cam { x: number; y: number }
let cam: Cam | null = null, S = MIN_S, viewW = 390, viewH = 400;
/** What the camera fits (logical px): the shop and its queue, tight. Across, the building's own
 *  corners: the queue stands on the pavement from the entrance round the front corner, which is
 *  inside that width, so the pavement past the corners (empty street) is left out. Down, the top of the back walls to
 *  the front corner's pavement, where the queue turns. FIT_PAD of margin round it. */
const bounds = (L: MapLayout): { x0: number; x1: number; y0: number; y1: number } => ({
  x0: pt(0, L.D).x - FIT_PAD, x1: pt(L.W, 0).x + FIT_PAD,
  y0: pt(0, 0).y - WALL - FIT_PAD, y1: pt(L.W + PAVE, L.D + PAVE).y + FIT_PAD,
});
/** The scale that fits the whole shop into a view w x h CSS px, within [MIN_S, MAX_S]. */
export function fitScale(L: MapLayout, w: number, h: number): number {
  const b = bounds(L);
  return Math.max(MIN_S, Math.min(MAX_S, w / (b.x1 - b.x0), h / (b.y1 - b.y0)));
}
/** Does the whole shop fit the canvas now (no pan needed)? */
export function mapFits(): boolean {
  const L = lay; if (!L) return false;
  const b = bounds(L);
  return (b.x1 - b.x0) * S <= viewW + 0.5 && (b.y1 - b.y0) * S <= viewH + 0.5;
}
function clampCam(L: MapLayout): void {
  if (!cam) return;
  const b = bounds(L), w = viewW / S, h = viewH / S;
  cam.x = b.x1 - b.x0 <= w ? (b.x0 + b.x1 - w) / 2 : Math.min(b.x1 - w, Math.max(b.x0, cam.x));
  cam.y = b.y1 - b.y0 <= h ? (b.y0 + b.y1 - h) / 2 : Math.min(b.y1 - h, Math.max(b.y0, cam.y));
}
/** The map's one scale: about VIEW_FRAC of the fitted width (the shop and its queue, bounds) on
 *  screen, so S = (canvas width / bounds width) / VIEW_FRAC: on a phone, where the width sets the fit, that is the
 *  fitted scale / 0.7. Never under the fitted scale (a screen where the height sets the fit), never over MAX_S. A swipe
 *  pans over the rest (clampCam). Only a screen so wide that MAX_S stops it (over ~1000 CSS px) shows the whole shop's
 *  width, centred, with the street's colour either side. */
export const VIEW_FRAC = 0.7;
export function viewScale(L: MapLayout, w: number, h: number): number {
  const b = bounds(L);
  return Math.max(fitScale(L, w, h), Math.min(MAX_S, w / (VIEW_FRAC * (b.x1 - b.x0))));
}
/** The opening view (every shift start and new shop): the entrance, the queue outside it and the front of the hall. */
function homeCam(L: MapLayout): void {
  const ps = [pt(L.W, (L.door[0] + L.door[1]) / 2, 40), pt(L.W, L.D), pt(L.W + PAVE, L.D + PAVE), ...queueSpots(L, [4, 4, 4]).flat().map(([u, v]) => pt(u, v, 60))];
  const xs = ps.map(p => p.x), ys = ps.map(p => p.y), w = viewW / S, h = viewH / S;
  const c = { x: (Math.min(...xs) + Math.max(...xs)) / 2, y: (Math.min(...ys) + Math.max(...ys)) / 2 };
  // the entrance stays in view, clear of the edges, however long the queue's run round the corner
  const d = ps[0] ?? c, m = w / 2 - 80;
  c.x = Math.min(d.x + m, Math.max(d.x - m, c.x));
  cam = { x: c.x - w / 2, y: c.y - h / 2 };
  clampCam(L);
}

