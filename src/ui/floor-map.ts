// Customer label -> look (the atlas's looks rules): the first matching rule gives member k its
// candidates; FNV-1a of "<group id>:<member index>" picks the start; earlier members' looks are skipped.
function fnv1a(s: string): number {
  let h = 0x811c9dc5;
  for (const b of new TextEncoder().encode(s)){ h ^= b; h = Math.imul(h, 0x01000193) >>> 0; }
  return h >>> 0;
}
const lookCache = new Map<string, string[]>();
export function looksOf(gid: number, label: string, size: number): string[] {
  const key = String(gid) + '|' + label + '|' + String(size), hit = lookCache.get(key); if (hit) return hit;
  const L = atlas?.looks, all = L?.customers ?? ['worker'], out: string[] = [];
  const rule = L?.rules.find(r => new RegExp(r.pattern).test(label));
  for (let m = 0; m < size; m++){
    const cands = rule ? rule.members[Math.min(m, rule.members.length - 1)] ?? all : all;
    const start = fnv1a(String(gid) + ':' + String(m)) % cands.length;
    let pick = cands[start] ?? 'worker';
    for (let i = 0; i < cands.length; i++){ const c = cands[(start + i) % cands.length]; if (c && !out.includes(c)){ pick = c; break; } }
    out.push(pick);
  }
  lookCache.set(key, out);
  return out;
}
/** Draws atlas part `name` with its anchor on logical point (x, y); mirrored about the anchor; `rows`: only the top rows. */
function part(name: string, x: number, y: number, mirror = false, rows?: number, rowsAnchor?: number): boolean {
  const A = atlas, p = A?.parts[name]; if (!A || !p) return false;
  const img = A.pages[p.page]; if (!img) return false;
  const c = cx(), h = rows ?? p.h, ay = rowsAnchor ?? p.anchor[1];
  c.save(); c.translate(x, y);
  if (mirror) c.scale(-1, 1);
  const ax = mirror ? p.anchor[0] : p.anchor[0];
  c.drawImage(img, p.x, p.y, p.w, h, -ax / 2, -ay / 2, p.w / 2, h / 2);
  c.restore();
  return true;
}
const sprite = (look: string, face: Facing): { name: string; mirror: boolean } =>
  face === '+v' ? { name: look + '_q_front', mirror: false } : face === '+u' ? { name: look + '_q_front', mirror: true }
    : face === '-u' ? { name: look + '_q_back', mirror: false } : { name: look + '_q_back', mirror: true };
/** A person at floor point (u, v) facing `face`: standing, or seated at seat height `seat` (cut at the hips). */
function person(u: number, v: number, face: Facing, who: Who, seat: number | null): { x: number; y: number } {
  const art = artNow(), back = face === '-u' || face === '-v';
  if (art){
    const sp = sprite(who.look, face), p = atlas?.parts[sp.name];
    if (p){
      if (seat === null){ shadowFeet(u, v, p.w * 0.19); const f = pt(u, v); part(sp.name, f.x, f.y, sp.mirror); return { x: f.x, y: f.y - p.anchor[1] / 2 }; }
      const hips = p.hips ?? p.h * 0.53, f = pt(u, v, seat);
      part(sp.name, f.x, f.y, sp.mirror, Math.ceil(hips), hips);
      return { x: f.x, y: f.y - hips / 2 };
    }
  }
  if (seat === null){ shadowFeet(u, v, 12); const f = pt(u, v); codePerson(f.x, f.y, PERSON, who, back, false); return { x: f.x, y: f.y - PERSON }; }
  // seated: the hips (row 21 of 30) sit at the seat
  const f = pt(u, v, seat), y = f.y + PERSON * 9 / 30;
  codePerson(f.x, y, PERSON, who, back, true);
  return { x: f.x, y: y - PERSON };
}

