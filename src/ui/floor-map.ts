/** Floor point (u, v, z) in CSS px of the floor canvas now (tests tap there). */
export function mapToScreen(u: number, v: number, z = 0): { x: number; y: number } {
  const p = pt(u, v, z), c = cam ?? { x: 0, y: 0 };
  return { x: (p.x - c.x) * S, y: (p.y - c.y) * S };
}
const HEADS = 120;   // logical px over the floor that a seated diner's head reaches: tapping the diners taps their table
/** A table's tap target now (CSS px of the floor canvas): its footprint up to its diners' heads, grown about its middle
 *  to at least TAP x TAP pt however small the fitted scale; where two overlap the nearer middle wins (mapHit). */
export function tableRect(tb: MapTable): { x: number; y: number; w: number; h: number } {
  const [u0, u1, v0, v1] = tb.box, ps = [mapToScreen(u0, v0), mapToScreen(u1, v0), mapToScreen(u1, v1), mapToScreen(u0, v1)];
  let x0 = Math.min(...ps.map(p => p.x)), x1 = Math.max(...ps.map(p => p.x)), y0 = Math.min(...ps.map(p => p.y)) - HEADS * S, y1 = Math.max(...ps.map(p => p.y));
  if (x1 - x0 < TAP){ const m = (x0 + x1) / 2; x0 = m - TAP / 2; x1 = m + TAP / 2; }
  if (y1 - y0 < TAP){ const m = (y0 + y1) / 2; y0 = m - TAP / 2; y1 = m + TAP / 2; }
  return { x: x0, y: y0, w: x1 - x0, h: y1 - y0 };
}

