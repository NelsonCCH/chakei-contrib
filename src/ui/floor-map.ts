let X: CanvasRenderingContext2D | null = null;
const cx = (): CanvasRenderingContext2D => must(X, 'map canvas');
function quad(u0: number, u1: number, v0: number, v1: number, z: number, fill: string): void {
  const c = cx(), a = pt(u0, v0, z), b = pt(u1, v0, z), d = pt(u1, v1, z), e = pt(u0, v1, z);
  c.beginPath(); c.moveTo(a.x, a.y); c.lineTo(b.x, b.y); c.lineTo(d.x, d.y); c.lineTo(e.x, e.y); c.closePath(); c.fillStyle = fill; c.fill();
}
function polyP(ps: { x: number; y: number }[], fill: string, stroke?: string): void {
  const c = cx(); c.beginPath(); ps.forEach((p, i) => { if (i) c.lineTo(p.x, p.y); else c.moveTo(p.x, p.y); }); c.closePath();
  c.fillStyle = fill; c.fill(); if (stroke){ c.strokeStyle = stroke; c.lineWidth = 1; c.stroke(); }
}
/** An iso box over [u0, u1] x [v0, v1], from z0 up h: top, the +v face (down-left), the +u face (down-right). */
function box(u0: number, u1: number, v0: number, v1: number, z0: number, h: number, top: string, left: string, right: string, edge: string | null = INK): void {
  const z1 = z0 + h;
  polyP([pt(u0, v1, z0), pt(u1, v1, z0), pt(u1, v1, z1), pt(u0, v1, z1)], left, edge ?? undefined);
  polyP([pt(u1, v0, z0), pt(u1, v1, z0), pt(u1, v1, z1), pt(u1, v0, z1)], right, edge ?? undefined);
  polyP([pt(u0, v0, z1), pt(u1, v0, z1), pt(u1, v1, z1), pt(u0, v1, z1)], top, edge ?? undefined);
}
function shadowQuad(u: number, v: number, a: number, b: number, alpha: number): void { quad(u - a, u + a, v - b, v + b, 0, `rgba(70,35,30,${String(alpha)})`); }
function shadowFeet(u: number, v: number, w: number): void {
  const c = cx(), p = pt(u, v); c.fillStyle = 'rgba(70,35,30,.28)'; c.beginPath(); c.ellipse(p.x, p.y, w, w / 2, 0, 0, Math.PI * 2); c.fill();
}

